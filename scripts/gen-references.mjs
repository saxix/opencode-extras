#!/usr/bin/env node
// Generate the reference pages under docs/reference/ from the definitions in
// src/. The pages are generated artifacts: edit the sources (frontmatter and
// the plugin READMEs), then run this script. tests/content-docs.test.mjs
// fails when a generated page is stale.
import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = path.resolve(__dirname, '..');
const SRC = path.join(REPO_ROOT, 'src');
const DOCS_REF = path.join(REPO_ROOT, 'docs', 'reference');

const isSourceItem = name => !name.startsWith('.') && !name.startsWith('~');

// Minimal frontmatter reader: enough for the flat `key: value` fields the
// generator needs. Multi-line values are not part of the definitions contract.
function readFrontmatter(file) {
  const text = fs.readFileSync(file, 'utf8');
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return {};
  const data = {};
  for (const line of match[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!kv) continue;
    let value = kv[2].trim();
    if (
      (value.startsWith("'") && value.endsWith("'")) ||
      (value.startsWith('"') && value.endsWith('"'))
    ) {
      value = value.slice(1, -1);
    }
    data[kv[1]] = value.replace(/\s+/g, ' ').trim();
  }
  return data;
}

function readmeTitle(file, fallback) {
  if (!fs.existsSync(file)) return fallback;
  const first = fs.readFileSync(file, 'utf8').split(/\r?\n/, 1)[0];
  const h1 = first.match(/^#\s+(.+)$/);
  return h1 ? h1[1].trim() : fallback;
}

function cell(value) {
  return String(value).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
}

function listAgents() {
  const dir = path.join(SRC, 'agents');
  return fs.readdirSync(dir)
    .filter(n => isSourceItem(n) && n.endsWith('.md'))
    .sort()
    .map(file => {
      const fm = readFrontmatter(path.join(dir, file));
      return {
        name: file.replace(/\.md$/, ''),
        mode: fm.mode || 'primary',
        hidden: fm.hidden === 'true',
        description: fm.description || '(no description)',
      };
    });
}

function listSkills() {
  const dir = path.join(SRC, 'skills');
  return fs.readdirSync(dir)
    .filter(n => isSourceItem(n) && fs.statSync(path.join(dir, n)).isDirectory())
    .sort()
    .map(name => {
      const entry = path.join(dir, name, 'SKILL.md');
      const fm = fs.existsSync(entry) ? readFrontmatter(entry) : {};
      const installed = fm.name || name;
      return {
        name,
        installed: installed.startsWith('sax-') ? installed : `sax-${installed}`,
        description: fm.description || '(no description)',
      };
    });
}

function listCommands() {
  const dir = path.join(SRC, 'commands');
  return fs.readdirSync(dir)
    .filter(n => isSourceItem(n) && n.endsWith('.md'))
    .sort()
    .map(file => {
      const fm = readFrontmatter(path.join(dir, file));
      return {
        name: file.replace(/\.md$/, ''),
        agent: fm.agent || '(default)',
        description: fm.description || '(no description)',
      };
    });
}

function listPlugins() {
  const dir = path.join(SRC, 'plugins');
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir)
    .filter(n => isSourceItem(n) && fs.statSync(path.join(dir, n)).isDirectory())
    .sort()
    .map(name => {
      const readme = path.join(dir, name, 'README.md');
      const body = fs.existsSync(readme)
        ? fs.readFileSync(readme, 'utf8').replace(/^#\s+.+\r?\n+/, '').trim()
        : '(no README)';
      return { name, title: readmeTitle(readme, name), body };
    });
}

const HEADER = '<!-- Generated by scripts/gen-references.mjs. Do not edit by hand. -->';

function renderAgents() {
  const agents = listAgents();
  const rows = agents
    .map(a => `| [\`${a.name}\`](#${a.name}) | ${a.mode} |`)
    .join('\n');
  const details = agents.map(a => {
    const hidden = a.hidden ? '\n- **Hidden:** yes (delegated subagent)' : '';
    return [
      `## ${a.name}`,
      '',
      `- **Mode:** ${a.mode}${hidden}`,
      `- **Source:** \`src/agents/${a.name}.md\``,
      '',
      a.description,
    ].join('\n');
  }).join('\n\n');
  return `${HEADER}
# Agent reference

Every agent in \`src/agents/\`, with its mode and purpose. Source of truth: the
frontmatter of each agent file; this page is generated from it.

## Summary

| Agent | Mode |
|---|---|
${rows}

${details}
`;
}

function renderSkills() {
  const skills = listSkills();
  const rows = skills
    .map(s => `| [\`${s.installed}\`](#${s.installed}) | \`${s.name}/\` |`)
    .join('\n');
  const details = skills.map(s => [
    `## ${s.installed}`,
    '',
    `- **Source:** \`src/skills/${s.name}/SKILL.md\``,
    '',
    s.description,
  ].join('\n')).join('\n\n');
  return `${HEADER}
# Skill reference

Every skill in \`src/skills/\`. Skills are installed under
\`DEST/skills/sax-<name>/\`; the installed name is shown in the heading.
Source of truth: each skill's \`SKILL.md\` frontmatter.

## Summary

| Installed skill | Source directory |
|---|---|
${rows}

${details}
`;
}

function renderCommands() {
  const commands = listCommands();
  const rows = commands
    .map(c => `| \`${c.name}\` | ${cell(c.agent)} | ${cell(c.description)} |`)
    .join('\n');
  return `${HEADER}
# Command reference

Every slash command in \`src/commands/\`. A command is a Markdown prompt body;
\`$ARGUMENTS\` receives the text typed after the command name. Commands without
an \`agent:\` key run in the TUI's current session.

| Command | Agent | Purpose |
|---|---|---|
${rows}
`;
}

function renderPlugins() {
  const plugins = listPlugins();
  const intro = `${HEADER}
# Plugin reference

TypeScript plugins in \`src/plugins/\`, registered through the
\`@opencode-ai/plugin\` API.

Plugins are **not** installed by \`scripts/install.mjs\`: copy the compiled
module into the opencode plugins directory, or declare it in the \`plugin\`
array of \`opencode.json\`/\`opencode.jsonc\`.
`;
  if (plugins.length === 0) return `${intro}\nNo plugins are present.\n`;
  return plugins.map(p => `${intro}
## ${p.title}

- **Source:** \`src/plugins/${p.name}/\`

${p.body}
`).join('\n');
}

// Map of repo-relative path -> file content.
export function renderReferences() {
  return {
    'docs/reference/agents.md': renderAgents(),
    'docs/reference/skills.md': renderSkills(),
    'docs/reference/commands.md': renderCommands(),
    'docs/reference/plugins.md': renderPlugins(),
  };
}

export function writeReferences() {
  fs.mkdirSync(DOCS_REF, { recursive: true });
  const files = renderReferences();
  for (const [rel, content] of Object.entries(files)) {
    fs.writeFileSync(path.join(REPO_ROOT, rel), content);
  }
  return Object.keys(files);
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  if (process.argv.includes('--check')) {
    let stale = 0;
    for (const [rel, content] of Object.entries(renderReferences())) {
      const abs = path.join(REPO_ROOT, rel);
      if (!fs.existsSync(abs) || fs.readFileSync(abs, 'utf8') !== content) {
        console.error(`stale: ${rel}`);
        stale += 1;
      }
    }
    if (stale > 0) {
      console.error('Run: node scripts/gen-references.mjs');
      process.exit(1);
    }
    console.log('docs/reference is up to date.');
  } else {
    const written = writeReferences();
    for (const rel of written) console.log(`wrote ${rel}`);
  }
}
