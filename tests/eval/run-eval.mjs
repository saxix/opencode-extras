#!/usr/bin/env node
// Live evaluation of the Reviewer agent against the fixtures under
// `tests/fixtures/reviewer/`.
//
// This is not part of `npm test`: it needs the `opencode` binary, a configured
// provider, and it costs tokens and time. It materializes each case into a
// temporary git repository, installs an `opencode.jsonc` that pins the subagent
// depth, runs the agent with `--print-logs`, and captures stdout plus the
// permission decisions from the log.
//
// Usage:
//   npm run eval:reviewer            # every case
//   npm run eval                     # same
//   node tests/eval/run-eval.mjs reviewer-clean-branch
//   node tests/eval/run-eval.mjs --model anthropic/claude-sonnet-4-5 reviewer-staged
//   node tests/eval/run-eval.mjs --keep      # keep the work directory
//
// The captured output and the automatic verdict are written to
// `tests/fixtures/reviewer/expectations.md`, which is committed so the latest
// evaluated output stays reviewable.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import {
  EXPECTATIONS,
  loadCases,
  loadSpec,
  materialize,
} from '../fixtures.mjs';
import { extractDenials, parseArgs, verdictOf } from './verdict.mjs';

const { keep, model, wanted } = parseArgs(process.argv.slice(2));

const CASES = loadCases();
const ALL = CASES.flatMap(({ dir, cases }) => cases.map(spec => ({ dir, spec })));
const selected = wanted.length === 0 ? ALL : ALL.filter(({ spec }) => wanted.includes(spec.id));

if (selected.length === 0) {
  console.error(`no case matches ${wanted.join(', ')}`);
  console.error(`known ids: ${ALL.map(({ spec }) => spec.id).join(', ')}`);
  process.exit(2);
}

if (!hasOpencode()) {
  console.error('the `opencode` binary is not on PATH; nothing to run');
  process.exit(2);
}

const workRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'opencode-reviewer-eval-'));
console.log(`work directory: ${workRoot}`);

const results = [];
for (const { dir, spec } of selected) {
  const full = loadSpec(dir, spec);
  const dest = path.join(workRoot, spec.id);
  fs.mkdirSync(dest, { recursive: true });
  materialize(dir, full, dest);

  const started = Date.now();
  const run = spawnSync(
    'opencode',
    [
      'run',
      '--standalone',
      '--agent',
      'reviewer',
      '--print-logs',
      ...(model ? ['--model', model] : []),
      spec.request,
    ],
    {
      cwd: dest,
      env: cleanEnv(dest),
      encoding: 'utf8',
      timeout: 900_000,
    }
  );
  const output = [run.stdout, run.stderr].filter(Boolean).join('\n');
  const denials = extractDenials(output);
  const verdict = verdictOf(full, output, denials);

  results.push({ spec, dest, output, denials, verdict, seconds: (Date.now() - started) / 1000 });
  console.log(`${spec.id}: ${verdict} (${denials.length} permission denials, ${Math.round((Date.now() - started) / 1000)}s)`);
  fs.writeFileSync(path.join(workRoot, `${spec.id}.output.md`), output);
}

writeReport(results, workRoot);

if (!keep) {
  fs.rmSync(workRoot, { recursive: true, force: true });
} else {
  console.log(`kept ${workRoot}`);
}

const failed = results.filter(r => r.verdict === 'FAIL');
process.exit(failed.length === 0 ? 0 : 1);

function hasOpencode() {
  const which = spawnSync('which', ['opencode'], { encoding: 'utf8' });
  return which.status === 0 && which.stdout.trim() !== '';
}

// The harness must run in the fixture directory, but opencode inherits the
// parent session through the environment: an inherited `OPENCODE_SESSION_ID` or
// `OPENCODE` makes the child attach to the caller's project and review the wrong
// tree. Strip every variable that carries that identity and repoint `PWD`, which
// opencode prefers over the actual process cwd when resolving its project.
function cleanEnv(dest) {
  const env = { ...process.env };
  for (const key of Object.keys(env)) {
    if (/^(OPENCODE|DIRENV)/i.test(key)) delete env[key];
  }
  env.PWD = dest;
  return env;
}

// A denied command is reported by the caller for each case; the rules live in
// `verdict.mjs` so the static suite covers them.

function writeReport(rows, root) {
  const lines = [
    '# Reviewer evaluation results',
    '',
    '<!-- Generated by tests/eval/run-eval.mjs. Do not edit by hand. -->',
    '',
    'The expectation of every case is anchored here. A run appends its captured output',
    'and its automatic verdict below; the expectations stay unchanged, so the same',
    'file records both the promise and the latest evidence.',
    '',
    '## Expectations',
    '',
  ];
  for (const { spec } of ALL) {
    lines.push(`- \`${spec.id}\` -- ${spec.expected}`);
  }
  lines.push('', '## Last run', '', `- date: ${new Date().toISOString()}`, `- model: ${model || 'agent default'}`, `- work directory: ${root}`, '');
  lines.push('| Case | Verdict | Denials | Expectation |');
  lines.push('|---|---|---|---|');
  for (const row of rows) {
    const status = row.verdict === 'PASS' ? 'PASS' : 'FAIL';
    const detail = status === 'PASS' ? 'automatic checks matched' : 'automatic checks did not match; read the output';
    lines.push(`| \`${row.spec.id}\` | ${status} | ${row.denials.length} | ${detail} |`);
  }
  for (const row of rows) {
    lines.push('', `### ${row.spec.id}`, '', `- request: \`${row.spec.request}\``, `- expectation: ${row.spec.expected}`, `- verdict: ${row.verdict}`, `- permission denials: ${row.denials.length}`, '');
    if (row.denials.length > 0) {
      lines.push('A denial is expected when the reviewer probes a command outside its allowlist;', 'the case fails only if the denied command was one it is supposed to be able to run.', '', 'Denied commands:', '');
      for (const d of row.denials.slice(0, 10)) lines.push(`- \`${d.command}\``);
      lines.push('');
    }
    lines.push('<details><summary>captured output</summary>', '', '```text', truncate(row.output, 12_000), '```', '', '</details>');
  }
  fs.writeFileSync(EXPECTATIONS, `${lines.join('\n')}\n`);
  console.log(`wrote ${path.relative(process.cwd(), EXPECTATIONS)}`);
}

function truncate(text, max) {
  if (text.length <= max) return text;
  return `${text.slice(0, max)}\n[... truncated ${text.length - max} characters]`;
}
